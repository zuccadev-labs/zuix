// Una sidebar por área, generada desde la carpeta. Las áreas se declaran en zudocs.config.json.
import type { SidebarsConfig } from "@docusaurus/plugin-content-docs";
import { loadZudocs } from "./scripts/config.mjs";

const sidebars: SidebarsConfig = {};
for (const area of loadZudocs().areas) sidebars[area.id] = [{ type: "autogenerated", dirName: area.id }];
export default sidebars;
